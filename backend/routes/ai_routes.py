import os
import uuid
from flask import Blueprint, request, jsonify, session, current_app
from werkzeug.utils import secure_filename
from backend.database import db
from backend.models import Project
from backend.ai.pipeline import process_blueprint

ai_bp = Blueprint('ai', __name__)

ALLOWED_EXTENSIONS = {'png', 'jpg', 'jpeg', 'bmp', 'pdf'}

def allowed_file(filename):
    return '.' in filename and filename.rsplit('.', 1)[1].lower() in ALLOWED_EXTENSIONS

@ai_bp.route('/upload', methods=['POST'])
def upload_blueprint():
    if 'file' not in request.files:
        return jsonify({'error': 'No file uploaded.'}), 400

    file = request.files['file']
    if file.filename == '':
        return jsonify({'error': 'No selected file.'}), 400

    if not allowed_file(file.filename):
        return jsonify({'error': 'Unsupported file format. Please upload PNG, JPG, JPEG, or PDF.'}), 400

    ext = file.filename.rsplit('.', 1)[1].lower()
    unique_filename = f"blueprint_{uuid.uuid4().hex[:10]}.{ext}"
    
    upload_folder = current_app.config['UPLOAD_FOLDER']
    os.makedirs(upload_folder, exist_ok=True)
    filepath = os.path.join(upload_folder, unique_filename)
    file.save(filepath)

    return jsonify({
        'message': 'File uploaded successfully!',
        'filename': unique_filename,
        'filepath': f"/uploads/{unique_filename}"
    }), 200

@ai_bp.route('/analyze', methods=['POST'])
def analyze_blueprint():
    data = request.get_json() or {}
    filename = data.get('filename')
    custom_scale = data.get('custom_scale')
    project_name = data.get('project_name', 'Blueprint 3D Project')

    if not filename:
        return jsonify({'error': 'Filename is required for analysis.'}), 400

    upload_folder = current_app.config['UPLOAD_FOLDER']
    filepath = os.path.join(upload_folder, filename)

    if not os.path.exists(filepath):
        return jsonify({'error': 'Uploaded file was not found on server.'}), 404

    if custom_scale:
        try:
            custom_scale = float(custom_scale)
        except ValueError:
            custom_scale = None

    try:
        # Run AI Computer Vision Pipeline
        results = process_blueprint(
            filepath, custom_scale=custom_scale, output_dir=upload_folder
        )

        user_id = session.get('user_id')
        
        # Save project to database
        project = Project(
            user_id=user_id,
            name=project_name,
            blueprint_filename=filename,
            thumbnail_url=f"/uploads/{filename}",
            processed_image_url=f"/uploads/{results['processed_image_filename']}",
            scale_ratio=results['scale_ratio'],
            structural_json=results
        )
        db.session.add(project)
        db.session.commit()

        results['project'] = project.to_dict()
        return jsonify(results), 200

    except Exception as e:
        return jsonify({
            'error': f'AI Detection Error: {str(e)}. Try uploading a clearer blueprint or click "Try Demo".'
        }), 500

@ai_bp.route('/demo', methods=['POST'])
def run_demo():
    data = request.get_json() or {}
    demo_type = data.get('demo_type', 'apartment')
    
    upload_folder = current_app.config['UPLOAD_FOLDER']
    sample_file = 'demo_apartment.png' if demo_type == 'apartment' else 'demo_villa.png'
    sample_path = os.path.join(upload_folder, sample_file)

    if not os.path.exists(sample_path):
        # Generate on the fly if missing
        from backend.samples.generate_samples import create_sample_blueprints
        create_sample_blueprints(upload_folder)

    try:
        results = process_blueprint(sample_path, output_dir=upload_folder)
        user_id = session.get('user_id')

        project = Project(
            user_id=user_id,
            name="Demo Modern Apartment" if demo_type == 'apartment' else "Demo Luxury Villa",
            description="Interactive 3D Demo generated by Blueprint3D AI Computer Vision Engine.",
            blueprint_filename=sample_file,
            thumbnail_url=f"/uploads/{sample_file}",
            processed_image_url=f"/uploads/{results['processed_image_filename']}",
            scale_ratio=results['scale_ratio'],
            structural_json=results
        )
        db.session.add(project)
        db.session.commit()

        results['project'] = project.to_dict()
        return jsonify(results), 200

    except Exception as e:
        return jsonify({'error': f'Demo generation error: {str(e)}'}), 500
